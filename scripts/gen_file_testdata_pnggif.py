def verify():
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, IMGIO_DUMP_DIR=d)
        subprocess.run(["cargo", "test", "--release", "--features", "png,gif", "--test", "file_png",
                        "--test", "file_gif", "--", "--ignored", "dump_encoded"], check=True, env=env, cwd=ROOT)
        for fmt, ext in (("png", ".png"), ("gif", ".gif")):
            lines = []
            for name in sorted(os.listdir(d)):
                if not name.endswith(ext):
                    continue
                stem = name[: -len(ext)]
                data = open(os.path.join(d, name), "rb").read()
                # <stem>.expected: raw frames (Pillow layout) the file must decode to
                exp = open(os.path.join(d, stem + ".expected"), "rb").read()
                meta = open(os.path.join(d, stem + ".meta")).read().split()
                mode, w, h = meta[0], int(meta[1]), int(meta[2])
                im = Image.open(io.BytesIO(data))
                got = b""
                for fr in ImageSequence.Iterator(im):
                    if mode == "I;16":
                        a = np.asarray(fr).astype("<u2")
                    elif mode == "RGB16":  # Pillow reduces 16-bit color: use libpng
                        import imagecodecs

                        a = imagecodecs.png_decode(data).astype("<u2")
                    else:
                        a = np.asarray(fr.convert(mode))
                    got += a.tobytes()
                assert got == exp, f"{name}: Pillow decode differs from the encoder input"
                lines.append(f"{stem} {fnv(data):016x}")
            out = OUT_PNG if fmt == "png" else OUT_GIF
            with open(os.path.join(out, "encoded_verified.txt"), "w") as f:
                f.write("# imgio encoder output decoded exactly by Pillow (scripts/gen_file_testdata_pnggif.py --verify)\n")
                f.write("\n".join(lines) + "\n")
            print(fmt, len(lines), "encoded files verified")


