import numpy as np
from PIL import Image, ImageSequence

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT_PNG = os.path.join(ROOT, "testdata", "file", "png")
OUT_GIF = os.path.join(ROOT, "testdata", "file", "gif")


def fnv(b):
    h = 0xCBF29CE484222325
    for x in b:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def le_bytes(a):
    a = np.ascontiguousarray(a)
    if a.dtype == np.uint16:
        return a.astype("<u2").tobytes()
    return a.astype(np.uint8).tobytes()


class Manifest:
    def __init__(self):
        self.lines = []

    def image(self, name, idx, fmt, arr, delay=(0, 1)):
        h, w = arr.shape[:2]
        self.lines.append(f"{name} {idx} {fmt} {w} {h} {delay[0]} {delay[1]} {fnv(le_bytes(arr)):016x}")

    def anim(self, name, loops, frames):
        self.lines.append(f"{name} * loops {loops} frames {frames}")

    def write(self, path):
        with open(path, "w") as f:
            f.write("# generated by scripts/gen_file_testdata_pnggif.py\n")
            f.write("\n".join(self.lines) + "\n")


