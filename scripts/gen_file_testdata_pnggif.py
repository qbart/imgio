def chunk(t, d):
    return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)


CHANNELS = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}
ADAM7 = [(0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4), (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2)]


def pack_row(row, depth):
    """row: (w, c) samples -> bytes."""
    flat = row.reshape(-1)
    if depth == 16:
        return flat.astype(">u2").tobytes()
    if depth == 8:
        return flat.astype(np.uint8).tobytes()
    per = 8 // depth
    out = bytearray((len(flat) * depth + 7) // 8)
    for i, v in enumerate(flat):
        out[i // per] |= (int(v) & ((1 << depth) - 1)) << (8 - depth * (i % per + 1))
    return bytes(out)


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def filter_rows(rows, bpp, seed):
    """Filters packed rows, cycling filter types 0..4 (all five are exercised)."""
    out = bytearray()
    prev = bytes(len(rows[0])) if rows else b""
    for y, r in enumerate(rows):
        ft = (y + seed) % 5
        f = bytearray(len(r))
        for i, x in enumerate(r):
            a = r[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            pred = [0, a, b, (a + b) // 2, paeth(a, b, c)][ft]
            f[i] = (x - pred) & 0xFF
        out.append(ft)
        out += f
        prev = r
    return bytes(out)


def image_data(samples, depth, interlace, seed=0):
    h, w, c = samples.shape
    bpp = max(1, c * depth // 8)
    if not interlace:
        rows = [pack_row(samples[y], depth) for y in range(h)]
        return filter_rows(rows, bpp, seed)
    raw = b""
    for (x0, y0, dx, dy) in ADAM7:
        sub = samples[y0::dy, x0::dx]
        if sub.shape[0] == 0 or sub.shape[1] == 0:
            continue
        rows = [pack_row(sub[y], depth) for y in range(sub.shape[0])]
        raw += filter_rows(rows, bpp, seed)
    return raw


def ihdr(w, h, depth, ct, interlace):
    return chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, depth, ct, 0, 0, int(interlace)))


def png_file(samples, depth, ct, interlace=False, plte=None, trns=None, pre=()):
    h, w = samples.shape[:2]
    out = b"\x89PNG\r\n\x1a\n" + ihdr(w, h, depth, ct, interlace)
    for c in pre:
        out += c
    if plte is not None:
        out += chunk(b"PLTE", bytes(plte))
    if trns is not None:
        out += chunk(b"tRNS", trns)
    raw = image_data(samples, depth, interlace)
    z = zlib.compress(raw, 9)
    # Two IDAT chunks (split data) to exercise chunk boundaries.
    half = len(z) // 2
    out += chunk(b"IDAT", z[:half]) + chunk(b"IDAT", z[half:])
    return out + chunk(b"IEND", b"")


def fctl(seq, w, h, x, y, dn, dd, dispose, blend):
    return chunk(b"fcTL", struct.pack(">IIIIIHHBB", seq, w, h, x, y, dn, dd, dispose, blend))


def apng_file(w, h, depth, ct, frames, plays, default=None, interlace=False, plte=None, trns=None):
    """frames: [(samples, x, y, (dn, dd), dispose, blend)]; default: samples of a default image
    that is not part of the animation (IDAT without fcTL)."""
    out = b"\x89PNG\r\n\x1a\n" + ihdr(w, h, depth, ct, interlace)
    out += chunk(b"acTL", struct.pack(">II", len(frames), plays))
    if plte is not None:
        out += chunk(b"PLTE", bytes(plte))
    if trns is not None:
        out += chunk(b"tRNS", trns)
    seq = 0
    if default is not None:
        out += chunk(b"IDAT", zlib.compress(image_data(default, depth, interlace), 9))
    for i, (s, x, y, delay, dispose, blend) in enumerate(frames):
        fh, fw = s.shape[:2]
        out += fctl(seq, fw, fh, x, y, delay[0], delay[1], dispose, blend)
        seq += 1
        z = zlib.compress(image_data(s, depth, interlace, i), 9)
        if i == 0 and default is None:
            out += chunk(b"IDAT", z)
        else:
            out += chunk(b"fdAT", struct.pack(">I", seq) + z)
            seq += 1
    return out + chunk(b"IEND", b"")


