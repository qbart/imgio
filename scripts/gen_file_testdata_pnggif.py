"""Generates testdata/file/png and testdata/file/gif (deterministic, offline reference tools).

Usage:
    python3 scripts/gen_file_testdata_pnggif.py            # test files + expected decodes
    python3 scripts/gen_file_testdata_pnggif.py --verify   # imgio encoder output vs Pillow

Needs numpy, Pillow 13, imagecodecs (libpng / libapng) and ffmpeg on PATH.

Files come from four writers: a small PNG / APNG / GIF writer in this script (every PNG color
type and bit depth, tRNS, Adam7, every APNG dispose / blend op, a default image outside the
animation, GIF local palettes, interlace, every disposal and loop count), Pillow, imagecodecs
and ffmpeg. Pixels are synthetic patterns (no third-party images).

`expected.txt` (one line per decoded image) holds what the reference decoders return, in
imgio's layout (16-bit samples little endian): `name index format width height delay_num
delay_den fnv1a64`, index `main` for `imgio::file::*::decode`, `0..` for the composited frames
of `decode_animation`, plus `name loops N frames M` per animation. References: imagecodecs
`png_decode` (libpng) for still PNG (cross-checked with Pillow for 8-bit), Pillow
`ImageSequence` for APNG / GIF frames, ffmpeg for APNG blending with partial alpha (Pillow
pastes with the alpha as a mask, which is not the APNG `OVER` operator; see
docs/spec/file_png.md).

`--verify` runs the ignored `dump_encoded` tests (they write imgio's encoder output and its input
to a scratch dir), decodes every file with Pillow, checks it is exact, and writes
`encoded_verified.txt` (name, fnv1a64 of the encoded bytes) that the regular tests check.
"""
