# PNG cases

def rnd(seed):
    return np.random.default_rng(seed)


def pattern8(w, h, c, seed):
    r = rnd(seed)
    y, x = np.mgrid[0:h, 0:w]
    base = np.stack([(x * 255 // max(w - 1, 1) + k * 60 + (y * 7)) % 256 for k in range(c)], -1)
    noise = r.integers(0, 40, (h, w, c))
    return ((base + noise) % 256).astype(np.uint8)


def gen_png_still(m):
    files = {}
    w, h = 13, 11
    for interlace in (False, True):
        sfx = "_i" if interlace else ""
        W, H = (w, h) if not interlace else (33, 17)
        for d in (1, 2, 4, 8, 16):
            s = rnd(d + 100 * interlace).integers(0, 1 << d, (H, W, 1))
            files[f"g{d}{sfx}"] = png_file(s, d, 0, interlace)
        for d in (1, 2, 4, 8):
            n = 1 << d
            s = rnd(10 + d).integers(0, n, (H, W, 1))
            plte = rnd(20 + d).integers(0, 256, n * 3).astype(np.uint8)
            files[f"p{d}{sfx}"] = png_file(s, d, 3, interlace, plte=plte)
            trns = bytes(rnd(30 + d).integers(0, 256, max(1, n - 1)).astype(np.uint8))
            files[f"p{d}_trns{sfx}"] = png_file(s, d, 3, interlace, plte=plte, trns=trns)
        for d in (8, 16):
            mx = (1 << d) - 1
            for ct, nm in ((2, "rgb"), (4, "ga"), (6, "rgba")):
                s = rnd(40 + d + ct).integers(0, mx + 1, (H, W, CHANNELS[ct]))
                files[f"{nm}{d}{sfx}"] = png_file(s, d, ct, interlace)
        # tRNS color keys: gray 2 / 8 / 16 and RGB 8 / 16 (key present in the image)
        for d in (2, 8, 16):
            s = rnd(50 + d).integers(0, 1 << d, (H, W, 1))
            key = int(s[1, 2, 0])
            files[f"g{d}_trns{sfx}"] = png_file(s, d, 0, interlace, trns=struct.pack(">H", key))
        for d in (8, 16):
            mx = (1 << d) - 1
            s = rnd(60 + d).integers(0, 4, (H, W, 3)) * (mx // 3)
            key = s[0, 0]
            files[f"rgb{d}_trns{sfx}"] = png_file(
                s, d, 2, interlace, trns=struct.pack(">HHH", *[int(v) for v in key]))
    # Color space chunks (sRGB / gAMA / cHRM / iCCP) on 8-bit RGB.
    s = pattern8(w, h, 3, 7)
    files["srgb_chunk"] = png_file(s, 8, 2, pre=[chunk(b"sRGB", b"\x00"), chunk(b"gAMA", struct.pack(">I", 45455))])
    chrm = struct.pack(">8I", 31270, 32900, 64000, 33000, 30000, 60000, 15000, 6000)
    files["gamma_chrm"] = png_file(s, 8, 2, pre=[chunk(b"gAMA", struct.pack(">I", 100000)), chunk(b"cHRM", chrm)])
    # Minimal ICC header (size, 'acsp' signature, no tags): only carried, never interpreted.
    icc = bytearray(132)
    icc[0:4] = struct.pack(">I", 132)
    icc[12:24] = b"mntrRGB XYZ "
    icc[36:40] = b"acsp"
    icc = bytes(icc)
    files["iccp"] = png_file(s, 8, 2, pre=[chunk(b"iCCP", b"test\x00\x00" + zlib.compress(icc))])
    # Pillow and ffmpeg encoders (8-bit RGBA, gray 16, ffmpeg Adam7).
    rgba = pattern8(29, 23, 4, 8)
    bio = io.BytesIO()
    Image.fromarray(rgba).save(bio, "PNG", optimize=True)
    files["pillow_rgba"] = bio.getvalue()
    g16 = rnd(9).integers(0, 65536, (23, 29)).astype(np.uint16)
    bio = io.BytesIO()
    Image.fromarray(g16).save(bio, "PNG")
    files["pillow_g16"] = bio.getvalue()
    pal = Image.fromarray(pattern8(29, 23, 3, 9) // 64 * 64).quantize(16)
    bio = io.BytesIO()
    pal.save(bio, "PNG", transparency=3)
    files["pillow_p4_trns"] = bio.getvalue()
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "src.rgba")
        open(src, "wb").write(pattern8(30, 21, 4, 11).tobytes())
        dst = os.path.join(d, "out.png")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgba", "-s", "30x21",
                        "-i", src, "-flags", "+ildct", "-pred", "mixed", "-frames:v", "1", dst], check=True)
        files["ffmpeg_rgba_i"] = open(dst, "rb").read()
    for name, data in files.items():
        open(os.path.join(OUT_PNG, name + ".png"), "wb").write(data)
        fmt, a = png_reference(data)
        # 8-bit: libpng and Pillow must agree (except low bit depth gray tRNS: Pillow compares
        # the unscaled key with the scaled samples)
        if fmt in MODE_FMT.values() and not name.startswith(("g2_trns", "g1_trns", "g4_trns")):
            p, _ = pillow_frames(data, fmt)
            assert np.array_equal(p[0][0].reshape(a.shape), a), name
        m.image(name, "main", fmt, a)


def apng_case(m, name, data, fmt, w, h, plays, delays, default=False, pillow_ok=True, ic_ok=True, ff=True):
    """Reference: ffmpeg for 8-bit files, imagecodecs (libpng APNG) for 16-bit and palette files
    (ffmpeg blends palette frames in index space); cross-checked with imagecodecs and Pillow
    where they implement the case correctly. `default`: the file has a default image outside the
    animation (Pillow / imagecodecs return it as frame 0)."""
    open(os.path.join(OUT_PNG, name + ".png"), "wb").write(data)
    ic = imagecodecs_frames(data, fmt)
    if default:
        ic = ic[1:]
    if fmt in FF_PIX and ff:
        frames = ffmpeg_frames(data, w, h, fmt)
        if ic_ok:
            assert len(ic) == len(frames) and all(np.array_equal(a.reshape(b.shape), b) for a, b in zip(ic, frames)), name
    else:
        frames = ic
    if pillow_ok:
        pf, _ = pillow_frames(data, fmt)
        pf = [f for f, _ in pf][1 if default else 0:]
        assert len(pf) == len(frames) and all(np.array_equal(a.reshape(b.shape), b) for a, b in zip(pf, frames)), name
    assert len(frames) == len(delays), (name, len(frames), len(delays))
    m.image(name, "main", fmt, png_reference(data)[1])
    for i, (f, d) in enumerate(zip(frames, delays)):
        m.image(name, i, fmt, f, d)
    m.anim(name, plays, len(frames))


def gen_apng(m):
    W, H = 24, 20
    r = rnd(70)

    def rgba_block(fw, fh, seed, binary=True):
        a = pattern8(fw, fh, 4, seed)
        if binary:
            a[..., 3] = np.where(rnd(seed).random((fh, fw)) < 0.3, 0, 255)
        return a

    # Every dispose / blend op with binary alpha (Pillow composites these exactly).
    fr = [
        (rgba_block(W, H, 1), 0, 0, (1, 10), 0, 0),        # NONE, SOURCE (full canvas)
        (rgba_block(10, 8, 2), 3, 4, (5, 100), 1, 1),      # BACKGROUND, OVER
        (rgba_block(12, 9, 3), 10, 9, (0, 0), 2, 1),       # PREVIOUS, OVER (delay 0/0 -> 0/100)
        (rgba_block(8, 12, 4), 14, 2, (3, 0), 0, 0),       # NONE, SOURCE (den 0 -> 100)
        (rgba_block(W, 6, 5), 0, 14, (1, 1), 2, 1),        # PREVIOUS, OVER (last)
    ]
    data = apng_file(W, H, 8, 6, fr, 0)
    delays = [(1, 10), (5, 100), (0, 100), (3, 100), (1, 1)]
    # Pillow: PREVIOUS after an OVER frame restores the blended canvas (it blends into its saved
    # copy), so it is not a reference here.
    apng_case(m, "apng_ops", data, "Rgba8Srgb", W, H, 0, delays, pillow_ok=False)
    # First frame disposes PREVIOUS (treated as BACKGROUND), interlaced frames.
    fr2 = [
        (rgba_block(W, H, 11), 0, 0, (2, 25), 2, 0),
        (rgba_block(9, 7, 12), 5, 5, (2, 25), 1, 1),
        (rgba_block(W, H, 13), 0, 0, (2, 25), 0, 1),
    ]
    data = apng_file(W, H, 8, 6, fr2, 3, interlace=True)
    # Pillow 13 fails on interlaced APNG frames after the first.
    apng_case(m, "apng_interlaced", data, "Rgba8Srgb", W, H, 3, [(2, 25)] * 3, pillow_ok=False)
    # Default image not part of the animation (IDAT before the first fcTL).
    default = rgba_block(W, H, 20)
    default[..., 3] = 255
    fr3 = [
        (rgba_block(W, H, 21), 0, 0, (1, 30), 1, 0),
        (rgba_block(7, 5, 22), 2, 3, (1, 30), 0, 1),
    ]
    data = apng_file(W, H, 8, 6, fr3, 2, default=default)
    apng_case(m, "apng_default_hidden", data, "Rgba8Srgb", W, H, 2, [(1, 30)] * 2, default=True)
    # Palette + tRNS, gray + alpha and RGB (no alpha: OVER == SOURCE).
    n = 16
    plte = r.integers(0, 256, n * 3).astype(np.uint8)
    plte[:3] = 0  # the transparent entry is black (Pillow keeps the RGB of transparent pixels)
    trns = bytes([0] + [255] * (n - 1))
    pal = [
        (r.integers(0, n, (H, W, 1)), 0, 0, (1, 20), 0, 0),
        (r.integers(0, n, (6, 9, 1)), 4, 4, (1, 20), 1, 1),
        (r.integers(0, n, (8, 8, 1)), 12, 10, (1, 20), 2, 1),
        (r.integers(0, n, (5, 5, 1)), 1, 13, (1, 20), 0, 0),
    ]
    data = apng_file(W, H, 4, 3, pal, 0, plte=plte, trns=trns)
    apng_case(m, "apng_palette", data, "Rgba8Srgb", W, H, 0, [(1, 20)] * 4, ff=False, pillow_ok=False)

    def ga_block(fw, fh, seed):
        a = r.integers(0, 256, (fh, fw, 2))
        a[..., 1] = np.where(rnd(seed).random((fh, fw)) < 0.4, 0, 255)
        return a

    ga = [
        (ga_block(W, H, 31), 0, 0, (7, 100), 1, 0),
        (ga_block(10, 10, 32), 2, 2, (7, 100), 0, 1),
        (ga_block(6, 9, 33), 15, 8, (7, 100), 2, 0),
        (ga_block(W, 4, 34), 0, 0, (7, 100), 0, 1),
    ]
    data = apng_file(W, H, 8, 4, ga, 1)
    apng_case(m, "apng_ga", data, "Rg8Unorm", W, H, 1, [(7, 100)] * 4)
    rgb = [
        (r.integers(0, 256, (H, W, 3)), 0, 0, (1, 15), 0, 0),
        (r.integers(0, 256, (8, 11, 3)), 6, 3, (1, 15), 2, 0),
        (r.integers(0, 256, (9, 4, 3)), 19, 11, (1, 15), 1, 0),
    ]
    data = apng_file(W, H, 8, 2, rgb, 0)
    apng_case(m, "apng_rgb", data, "Rgb8Srgb", W, H, 0, [(1, 15)] * 3)
    # Partial alpha OVER. Reference: imagecodecs, which uses the APNG spec's sample formula
    # (integer division); ffmpeg rounds instead (off by one), Pillow pastes with alpha as a mask
    # (not the OVER operator).
    pa = [
        (pattern8(W, H, 4, 41), 0, 0, (1, 10), 0, 0),
        (pattern8(11, 9, 4, 42), 4, 6, (1, 10), 0, 1),
        (pattern8(W, H, 4, 43), 0, 0, (1, 10), 0, 1),
    ]
    data = apng_file(W, H, 8, 6, pa, 0)
    apng_case(m, "apng_partial_alpha", data, "Rgba8Srgb", W, H, 0, [(1, 10)] * 3, pillow_ok=False, ff=False)
    # 16-bit RGBA with partial alpha, every op (reference: imagecodecs; Pillow is 8-bit only).
    r16 = rnd(77)
    fr16 = [
        (r16.integers(0, 65536, (H, W, 4)), 0, 0, (1, 10), 1, 0),
        (r16.integers(0, 65536, (7, 9, 4)), 4, 6, (1, 10), 2, 1),
        (r16.integers(0, 65536, (10, 12, 4)), 10, 2, (1, 10), 0, 1),
        (r16.integers(0, 65536, (5, 5, 4)), 1, 1, (1, 10), 0, 0),
    ]
    for f in fr16:
        f[0][..., 3][r16.random(f[0].shape[:2]) < 0.2] = 0
