# Expected decodes (imgio layout)

def png_reference(data):
    """libpng (imagecodecs) decode with tRNS -> alpha, in imgio's format."""
    import imagecodecs

    a = imagecodecs.png_decode(data)
    if a.ndim == 2:
        a = a[..., None]
    c = a.shape[2]
    if a.dtype == np.uint16:
        fmt = {1: "R16Unorm", 2: "Rg16Unorm", 3: "Rgba16Unorm", 4: "Rgba16Unorm"}[c]
        if c == 3:
            a = np.concatenate([a, np.full(a.shape[:2] + (1,), 65535, np.uint16)], 2)
    else:
        fmt = {1: "R8Unorm", 2: "Rg8Unorm", 3: "Rgb8Srgb", 4: "Rgba8Srgb"}[c]
    return fmt, a


def pillow_rgba(im):
    if im.mode in ("RGBA",):
        return np.asarray(im)
    return np.asarray(im.convert("RGBA"))


MODE_FMT = {"L": "R8Unorm", "LA": "Rg8Unorm", "RGB": "Rgb8Srgb", "RGBA": "Rgba8Srgb"}


def pillow_frames(data, target_fmt):
    """Composited frames from Pillow, converted to imgio's layout for `target_fmt`."""
    im = Image.open(io.BytesIO(data))
    out = []
    for fr in ImageSequence.Iterator(im):
        f = fr.copy()
        if target_fmt == "Rgba8Srgb":
            a = np.asarray(f.convert("RGBA"))
        elif target_fmt == "Rgb8Srgb":
            a = np.asarray(f.convert("RGB"))
        elif target_fmt == "R8Unorm":
            a = np.asarray(f.convert("L"))
        elif target_fmt == "Rg8Unorm":
            a = np.asarray(f.convert("LA"))
        else:
            raise ValueError(target_fmt)
        out.append((a, fr.info.get("duration", 0)))
    return out, im.info.get("loop", None)


FF_PIX = {"Rgba8Srgb": ("rgba", 4), "Rgb8Srgb": ("rgb24", 3), "Rg8Unorm": ("ya8", 2), "R8Unorm": ("gray", 1)}


def ffmpeg_frames(data, w, h, fmt="Rgba8Srgb"):
    """Composited APNG frames decoded by ffmpeg (APNG demuxer, one output frame per fcTL)."""
    pix, c = FF_PIX[fmt]
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "in.png")
        open(p, "wb").write(data)
        raw = subprocess.run(
            ["ffmpeg", "-v", "error", "-f", "apng", "-i", p, "-fps_mode", "passthrough", "-f", "rawvideo",
             "-pix_fmt", pix, "-"], check=True, capture_output=True).stdout
    n = len(raw) // (w * h * c)
    return [np.frombuffer(raw[i * w * h * c:(i + 1) * w * h * c], np.uint8).reshape(h, w, c) for i in range(n)]


def imagecodecs_frames(data, fmt):
    """Composited APNG frames from imagecodecs (libpng + APNG patch), hidden default image first."""
    import imagecodecs

    a = imagecodecs.apng_decode(data)
    if a.ndim == 3:
        a = a[..., None]
    if fmt == "Rgba16Unorm" and a.shape[-1] == 3:
        a = np.concatenate([a, np.full(a.shape[:-1] + (1,), 65535, np.uint16)], -1)
    return list(a)


