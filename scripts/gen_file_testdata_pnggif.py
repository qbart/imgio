# GIF writer

def lzw_encode(idx, mcs):
    clear, eoi = 1 << mcs, (1 << mcs) + 1
    bits, nbits, out = 0, 0, bytearray()

    def emit(code, size):
        nonlocal bits, nbits
        bits |= code << nbits
        nbits += size
        while nbits >= 8:
            out.append(bits & 0xFF)
            bits >>= 8
            nbits -= 8

    def reset():
        return {bytes([i]): i for i in range(clear)}, eoi + 1, mcs + 1

    table, nxt, size = reset()
    emit(clear, size)
    w = b""
    for k in idx:
        wk = w + bytes([k])
        if wk in table:
            w = wk
            continue
        emit(table[w], size)
        if nxt < 4095:
            table[wk] = nxt
            nxt += 1
            if nxt > (1 << size) and size < 12:
                size += 1
        else:
            emit(clear, size)
            table, nxt, size = reset()
        w = bytes([k])
    if w:
        emit(table[w], size)
    emit(eoi, size)
    if nbits:
        out.append(bits & 0xFF)
    return bytes(out)


def sub_blocks(b):
    out = bytearray()
    for i in range(0, len(b), 255):
        out.append(len(b[i:i + 255]))
        out += b[i:i + 255]
    return bytes(out) + b"\x00"


def table_bits(n):
    b = 1
    while (1 << b) < n:
        b += 1
    return b


def gif_file(w, h, frames, gpal=None, loop=None, bg=0):
    """frames: dicts with idx (h, w) array, x, y, delay, dispose, trans, lpal, interlace."""
    out = bytearray(b"GIF89a")
    flags = 0
    if gpal is not None:
        tb = table_bits(len(gpal) // 3)
        flags = 0x80 | ((tb - 1) << 4) | (tb - 1)
    out += struct.pack("<HHBBB", w, h, flags, bg, 0)
    if gpal is not None:
        out += bytes(gpal) + bytes(3 * (1 << tb) - len(gpal))
    if loop is not None:
        out += b"\x21\xff\x0bNETSCAPE2.0\x03\x01" + struct.pack("<H", loop) + b"\x00"
    for f in frames:
        t = f.get("trans")
        gf = (f.get("dispose", 0) << 2) | (1 if t is not None else 0)
        out += b"\x21\xf9\x04" + struct.pack("<BHB", gf, f.get("delay", 0), t or 0) + b"\x00"
        idx = f["idx"]
        fh, fw = idx.shape
        lpal = f.get("lpal")
        fl = 0x40 if f.get("interlace") else 0
        if lpal is not None:
            tb = table_bits(len(lpal) // 3)
            fl |= 0x80 | (tb - 1)
        out += b"\x2c" + struct.pack("<HHHHB", f.get("x", 0), f.get("y", 0), fw, fh, fl)
        if lpal is not None:
            out += bytes(lpal) + bytes(3 * (1 << tb) - len(lpal))
        rows = list(range(fh))
        if f.get("interlace"):
            rows = list(range(0, fh, 8)) + list(range(4, fh, 8)) + list(range(2, fh, 4)) + list(range(1, fh, 2))
        data = idx[rows].reshape(-1).astype(np.uint8)
        mcs = max(2, table_bits(int(data.max()) + 1))
        out += bytes([mcs]) + sub_blocks(lzw_encode(data.tobytes(), mcs))
    out += b"\x3b"
    return bytes(out)


def gif_case(m, name, data, loops, ndelays):
    open(os.path.join(OUT_GIF, name + ".gif"), "wb").write(data)
    frames, loop = pillow_frames(data, "Rgba8Srgb")
    # imgio: no NETSCAPE block -> 1 play; N -> N + 1 plays (browsers); 0 -> forever.
    exp = 1 if loop is None else (0 if loop == 0 else loop + 1)
    assert exp == loops, (name, loop, loops)
    assert len(frames) == ndelays, (name, len(frames))
    m.image(name, "main", "Rgba8Srgb", frames[0][0])
    for i, (f, dur) in enumerate(frames):
        m.image(name, i, "Rgba8Srgb", f, (dur // 10, 100))
    m.anim(name, loops, len(frames))


def gen_gif(m):
    r = rnd(90)
    W, H = 26, 19
    gpal = r.integers(0, 256, 32 * 3).astype(np.uint8)
    gpal[:3] = 0  # transparent entries are black: Pillow keeps the palette RGB of transparent pixels
    lpal = r.integers(0, 256, 8 * 3).astype(np.uint8)
    lpal[3 * 7:3 * 8] = 0
    # Still, global palette, not interlaced; and interlaced with a local palette.
    still = r.integers(0, 32, (H, W))
    gif_case(m, "still", gif_file(W, H, [dict(idx=still)], gpal), 1, 1)
    gif_case(m, "still_interlaced_local", gif_file(
        W, 37, [dict(idx=r.integers(0, 8, (37, W)), interlace=True, lpal=lpal)], gpal), 1, 1)
    # Transparency in the first frame (canvas starts transparent).
    t = r.integers(0, 32, (H, W))
    t[r.random((H, W)) < 0.3] = 0
    gif_case(m, "still_transparent", gif_file(W, H, [dict(idx=t, trans=0)], gpal, loop=None), 1, 1)
    # Animation: every disposal, offsets, local palettes, interlace, loop forever.
    f0 = r.integers(1, 32, (H, W))
    frames = [
        dict(idx=f0, delay=10, dispose=1, trans=0),
        dict(idx=r.integers(0, 32, (7, 9)), x=3, y=2, delay=20, dispose=2, trans=0),
        dict(idx=r.integers(0, 8, (8, 10)), x=12, y=8, delay=5, dispose=3, trans=7, lpal=lpal, interlace=True),
        dict(idx=r.integers(0, 32, (6, 6)), x=18, y=1, delay=0, dispose=1, trans=0),
        dict(idx=r.integers(0, 8, (H, 5)), x=0, y=0, delay=7, dispose=2, trans=7, lpal=lpal),
        dict(idx=r.integers(0, 32, (5, 12)), x=8, y=12, delay=3, dispose=1, trans=0),
    ]
    gif_case(m, "anim_disposal", gif_file(W, H, frames, gpal, loop=0), 0, len(frames))
    # Loop count 3 (-> 4 plays), no global palette.
    frames = [dict(idx=r.integers(0, 8, (H, W)), lpal=lpal, delay=4, dispose=1),
              dict(idx=r.integers(0, 8, (H, W)), lpal=lpal, delay=4, dispose=1)]
    gif_case(m, "anim_loop3_local", gif_file(W, H, frames, None, loop=3), 4, 2)
    # Pillow encoder: sub-rect frames, disposal 2 with transparency.
    ims = []
    for i in range(5):
        a = np.zeros((24, 32, 3), np.uint8)
        a[...] = (20, 40, 60)
        a[3 + i * 3:9 + i * 3, 2 + i * 5:10 + i * 5] = (250, 200 - 30 * i, 10)
        ims.append(Image.fromarray(a))
    bio = io.BytesIO()
    ims[0].save(bio, "GIF", save_all=True, append_images=ims[1:], duration=[50, 60, 70, 80, 90], loop=2)
    gif_case(m, "pillow_anim", bio.getvalue(), 3, 5)
    # ffmpeg encoder (transparency diffing, sub-rectangles).
    with tempfile.TemporaryDirectory() as d:
        dst = os.path.join(d, "out.gif")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "testsrc=size=32x24:rate=10",
                        "-frames:v", "6", "-loop", "0", dst], check=True)
        data = open(dst, "rb").read()
    gif_case(m, "ffmpeg_anim", data, 0, 6)


